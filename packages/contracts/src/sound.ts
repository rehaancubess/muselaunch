// ---------------------------------------------------------------------------
// Voiceover
// ---------------------------------------------------------------------------

/** Normalised word error rate above which a generated voiceover is regenerated once, then flagged. */
export const VOICEOVER_WER_THRESHOLD = 0.15;

/** Muse Voice Transcribe check of a voiceover against its script (stored on the voiceover track). */
export const VoiceoverCheck = z.object({
  /** Normalised word error rate (0 = identical words). */
  wer: z.number().min(0).max(10),
  passed: z.boolean(),
  /** TTS generations made (1, or 2 after one regeneration). */
  attempts: z.number().int().min(1).max(3),
  transcriptId: Id.optional(),
  model: z.string().max(60).optional(),
});
export type VoiceoverCheck = z.infer<typeof VoiceoverCheck>;

/** A spoken stretch inside a voiceover (track-local seconds, from Muse Voice Transcribe turns). */
export const SpeechRange = z.object({ startSec: z.number().min(0), endSec: z.number().min(0) });
export type SpeechRange = z.infer<typeof SpeechRange>;

// ---------------------------------------------------------------------------
// Workspace defaults
// ---------------------------------------------------------------------------

/**
 * New videos (and Autopilot) get original music + sound effects automatically. AI voiceover is
 * off by default: when on, storyboards that ask for narration get an external-TTS voice (labelled).
 */
export const WorkspaceSoundSettings = z.object({
  music: z.boolean().default(true),
  sfx: z.boolean().default(true),
  aiVoiceover: z.boolean().default(false),
  /** Built-in TTS voice (never a clone). */
  voice: z.string().min(1).max(40).optional(),
});
export type WorkspaceSoundSettings = z.infer<typeof WorkspaceSoundSettings>;
export const DEFAULT_SOUND_SETTINGS: WorkspaceSoundSettings = { music: true, sfx: true, aiVoiceover: false };

// ---------------------------------------------------------------------------
// Studio sound API (apps/api/src/routes/sound.ts)
// ---------------------------------------------------------------------------

/** `POST /compositions/:id/sound/music`: set the mood (new render), regenerate (new seed), volume, or remove. */
export const SoundMusicRequest = z.object({
  baseVersion: z.number().int().min(1),
  enabled: z.boolean().default(true),
  mood: MusicMood.optional(),
  /** New seed: a different take in the same mood. */
  regenerate: z.boolean().default(false),
  volume: z.number().min(0).max(1).optional(),
});
export type SoundMusicRequest = z.infer<typeof SoundMusicRequest>;

/** `POST /compositions/:id/sound/sfx`: automatic effects on (re-placed for the current scenes) or off. */
export const SoundSfxRequest = z.object({
  baseVersion: z.number().int().min(1),
  enabled: z.boolean(),
  volume: z.number().min(0).max(1).optional(),
});
export type SoundSfxRequest = z.infer<typeof SoundSfxRequest>;

/** `POST /compositions/:id/sound/voiceover`: AI voice (external TTS, verified) or your own recording. */
export const SoundVoiceoverRequest = z.discriminatedUnion("source", [
  z.object({ source: z.literal("tts"), baseVersion: z.number().int().min(1), voice: z.string().max(40).optional(), script: z.string().trim().min(1).max(4000).optional() }),
  /** A recorded/uploaded voice. `consent` is required unless the asset already carries it (or was recorded in-app). */
  z.object({ source: z.literal("recording"), baseVersion: z.number().int().min(1), assetId: Id, consent: ConsentInput.optional() }),
]);
export type SoundVoiceoverRequest = z.infer<typeof SoundVoiceoverRequest>;

/** `DELETE /compositions/:id/sound/voiceover?baseVersion=` body-less; query parsed with this. */
export const SoundRemoveVoiceoverQuery = z.object({ baseVersion: z.coerce.number().int().min(1) });
