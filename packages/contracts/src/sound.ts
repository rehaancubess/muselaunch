/** Parameters of one original music render. Same parameters → same bytes (cached per workspace). */
export const MusicParams = z.object({
  mood: MusicMood,
  /** Exact length of the track (seconds); the arrangement (intro, body, ending) is fitted to it. */
  durationSec: z.number().min(3).max(180),
  /** Any string; different seeds give different keys, progressions and patterns within the mood. */
  seed: z.string().min(1).max(120),
  /** Timeline times (s) that get a riser into a soft hit, snapped to the nearest beat. */
  accents: z.array(z.number().min(0).max(180)).max(12).default([]),
});
export type MusicParams = z.infer<typeof MusicParams>;

